package formats

import "testing"

func TestDate(t *testing.T) {
	checkFormat(t, Date, []string{"0000-02-29", "0001-01-01", "2000-02-29", "2024-02-29", "2024-04-30", "9999-12-31"}, []string{"", "2024-1-01", "2024-01-1", "2024/01/01", "1900-02-29", "2023-02-29", "2024-04-31", "2024-00-01", "2024-13-01", "2024-01-00", "2024-01-32", "2024-01-01\n", "２０２４-01-01", "2024-01-01T00:00:00Z"})
}
func TestTime(t *testing.T) {
	checkFormat(t, Time, []string{"00:00:00Z", "12:30:59z", "12:30:00.123456789Z", "23:59:60Z", "00:59:60+01:00", "22:59:60-01:00", "00:00:00+23:59", "12:00:00-00:00"}, []string{"", "12:00:00", "24:00:00Z", "12:60:00Z", "23:59:61Z", "12:00:60Z", "12:00:00+24:00", "12:00:00+00:60", "12:00:00+0000", "12:00:00.Z", "12:00:00.", "12:00:00Z\n", "1:00:00Z", "12:0:00Z", "12:00:0Z", "12:00:00.1", "12:00:00+aa:00", "aa:00:00Z", "23:59:60+01:00", "23:59:60-01:00", "12:00:00Zextra"})
}
func TestDateTime(t *testing.T) {
	checkFormat(t, DateTime, []string{"2024-02-29T12:30:00Z", "2024-02-29t12:30:00z", "2016-12-31T23:59:60Z"}, []string{"2024-02-29 12:30:00Z", "2024-02-30T12:30:00Z", "2024-02-29T12:30:00", "2024-02-29T12:30:00ZT", "T", "2024-01-01"})
}
func TestDuration(t *testing.T) {
	checkFormat(t, Duration, []string{"P1Y", "P1M", "P1D", "P0D", "P1Y2M3DT4H5M6S", "P1Y2M", "P1W", "PT1H", "PT1M", "PT1S", "P1DT1H"}, []string{"", "P", "PT", "P1Y3D", "PT1H5S", "P1.5D", "PT1.5S", "P1W2D", "p1d", "P-1D", "P1DT", "P1D\n"})
}
